from typing import Protocol

from projectctl.schemas.execution import EvidenceReference
from projectctl.schemas.task_claim import TaskClaim, TaskClaimRequest
from projectctl.schemas.task import NormalizedTask, TaskSnapshot


class TaskStoreReader(Protocol):
    def get(self, task_id: str) -> NormalizedTask: ...
    def list_all(self) -> list[NormalizedTask]: ...
    def list_ready(self) -> list[NormalizedTask]: ...
    def list_blocked(self) -> list[NormalizedTask]: ...
    def snapshot(self, *, tasks: list[NormalizedTask] | None = None) -> TaskSnapshot: ...


class TaskClaimer(Protocol):
    def claim(self, request: TaskClaimRequest) -> TaskClaim: ...
    def reconcile(self, request: TaskClaimRequest) -> TaskClaim | None: ...
    def validate(self, claim: TaskClaim) -> bool: ...
    def release(self, claim: TaskClaim) -> None: ...
    def release_legacy(self, task_id: str, *, actor: str) -> None: ...


class TaskCompletionWriter(Protocol):
    def complete(self, task_id: str, *, evidence: EvidenceReference) -> None: ...
    def mark_needs_decision(self, task_id: str, *, reason: str) -> None: ...

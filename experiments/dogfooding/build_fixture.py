#!/usr/bin/env python3
"""Build the fixed synthetic D1 task in a disposable local Git repository."""
from __future__ import annotations

import argparse
import hashlib
import os
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parent
OUTPUT_ROOT = ROOT / "fixture-output"
FILES = {
    "SPEC.md": """# Task: normalize user identifiers\n\nImplement `normalize_user_id(value)` in `user_id.py`. Accept strings only; trim surrounding whitespace and lowercase ASCII letters. Reject non-strings and empty results with `ValueError`. Do not alter `POLICY.md` or `test_user_id.py`.\n""",
    "POLICY.md": "Protected D1 fixture policy. Do not edit this file.\n",
    "user_id.py": """def normalize_user_id(value):\n    raise NotImplementedError\n""",
    "test_user_id.py": """import unittest\nfrom user_id import normalize_user_id\n\nclass NormalizeUserIdTests(unittest.TestCase):\n    def test_trim_and_lowercase(self):\n        self.assertEqual(normalize_user_id('  Alice  '), 'alice')\n    def test_empty_rejected(self):\n        with self.assertRaises(ValueError): normalize_user_id('  ')\n    def test_non_string_rejected(self):\n        with self.assertRaises(ValueError): normalize_user_id(None)\n\nif __name__ == '__main__': unittest.main()\n""",
}


def build(destination: Path) -> str:
    dest = destination.resolve()
    if not dest.is_relative_to(OUTPUT_ROOT.resolve()):
        raise ValueError("fixture destination must be inside experiments/dogfooding/fixture-output")
    if dest.exists() and any(dest.iterdir()):
        raise FileExistsError("destination exists and is not empty")
    dest.mkdir(parents=True, exist_ok=True)
    for name, content in FILES.items():
        (dest / name).write_text(content, encoding="utf-8")
    run = lambda *args: subprocess.run(["git", "-C", str(dest), *args], check=True, capture_output=True, text=True)
    run("init", "--quiet")
    run("config", "user.name", "D0 Fixture")
    run("config", "user.email", "d0-fixture@invalid.example")
    run("add", *FILES.keys())
    fixed_env = os.environ.copy()
    fixed_env.update({"GIT_AUTHOR_DATE": "2000-01-01T00:00:00+00:00", "GIT_COMMITTER_DATE": "2000-01-01T00:00:00+00:00"})
    subprocess.run(["git", "-C", str(dest), "commit", "--quiet", "-m", "D0 fixed baseline"], check=True, capture_output=True, text=True, env=fixed_env)
    return subprocess.run(["git", "-C", str(dest), "rev-parse", "HEAD"], check=True, capture_output=True, text=True).stdout.strip()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("name", help="new directory name under fixture-output")
    args = parser.parse_args()
    if Path(args.name).name != args.name or args.name in {".", ".."}:
        parser.error("name must be a single directory name")
    destination = OUTPUT_ROOT / args.name
    sha = build(destination)
    digest = hashlib.sha256((destination / "SPEC.md").read_bytes()).hexdigest()
    print(f"fixture={args.name} baseline_sha={sha} spec_sha256={digest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

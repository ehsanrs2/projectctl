#!/usr/bin/env python3
"""Create a fixed D1 fixture in a new external, operator-selected local Git repo."""
from __future__ import annotations

import argparse
import hashlib
import os
from pathlib import Path
import re
import subprocess

SOURCE_CHECKOUT = Path(__file__).resolve().parents[2]
FILES = {
    'SPEC.md': ("# Task: normalize user identifiers\n\n"
                "Implement "+'\x60'+"normalize_user_id(value)"+'\x60'+" in "+'\x60'+"user_id.py"+'\x60'+". "
                "Accept strings only; trim surrounding whitespace and lowercase "
                "ASCII letters A-Z only (do not lowercase non-ASCII letters). "
                "Preserve internal whitespace. Reject non-strings and "
                "empty results with "+'\x60'+"ValueError"+'\x60'+". Do not alter "+'\x60'+"POLICY.md"+'\x60'+" "
                "or "+'\x60'+"test_user_id.py"+'\x60'+".\n"),
    'POLICY.md': 'Protected D1 fixture policy. Do not edit this file.\n',
    'user_id.py': 'def normalize_user_id(value):\n    raise NotImplementedError\n',
    'test_user_id.py': '''import unittest
from user_id import normalize_user_id

class NormalizeUserIdTests(unittest.TestCase):
    def test_trim_and_lowercase(self):
        self.assertEqual(normalize_user_id('  Alice  '), 'alice')
    def test_empty_rejected(self):
        with self.assertRaises(ValueError): normalize_user_id('  ')
    def test_non_string_rejected(self):
        with self.assertRaises(ValueError): normalize_user_id(None)
    def test_only_ascii_lowercased(self):
        self.assertEqual(normalize_user_id('  ÄAÉB  '), 'ÄaÉb')
    def test_internal_whitespace_preserved(self):
        self.assertEqual(normalize_user_id('  A\\t B  '), 'a\\t b')
    def test_whitespace_trimmed(self):
        self.assertEqual(normalize_user_id('\\tAlice\\n'), 'alice')

if __name__ == '__main__': unittest.main()
''',
}


def validate_root(root: Path) -> Path:
    """Require an explicit, existing external directory, never a Git worktree."""
    if root.is_symlink() or not root.is_dir():
        raise ValueError('output-root must be a real, existing directory (not a symlink)')
    external = root.resolve()
    if external == SOURCE_CHECKOUT or external.is_relative_to(SOURCE_CHECKOUT):
        raise ValueError('output-root must be outside ProjectCTL source checkout')
    if SOURCE_CHECKOUT.is_relative_to(external):
        raise ValueError('output-root cannot be an ancestor of the ProjectCTL checkout')
    probe = subprocess.run(['git', '-C', str(external), 'rev-parse', '--show-toplevel'],
                           capture_output=True, text=True, check=False, timeout=5)
    if probe.returncode == 0:
        raise ValueError('output-root must not be inside any existing Git worktree')
    return external


def build(destination: Path, *, output_root: Path) -> str:
    root = validate_root(output_root)
    # A single leaf ensures the builder cannot traverse outside the selected root.
    if destination.parent.resolve() != root or not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_-]{0,63}', destination.name):
        raise ValueError('fixture destination must be a single safe name directly under output-root')
    if destination.exists() or destination.is_symlink():
        raise FileExistsError('fixture destination already exists; preserving it unchanged')
    destination.mkdir(mode=0o700)
    for name, content in FILES.items():
        (destination / name).write_text(content, encoding='utf-8')
    def run(*args: str) -> None:
        subprocess.run(['git', '-C', str(destination), *args], check=True,
                       capture_output=True, text=True, timeout=20)
    run('init', '--quiet')
    run('config', 'user.name', 'D0 Fixture')
    run('config', 'user.email', 'd0-fixture@invalid.example')
    run('add', *FILES.keys())
    fixed_env = os.environ.copy()
    fixed_env.update({'GIT_AUTHOR_DATE': '2000-01-01T00:00:00+00:00',
                      'GIT_COMMITTER_DATE': '2000-01-01T00:00:00+00:00'})
    subprocess.run(['git', '-C', str(destination), 'commit', '--quiet', '-m', 'D0 fixed baseline'],
                   check=True, capture_output=True, text=True, env=fixed_env, timeout=20)
    result = subprocess.run(['git', '-C', str(destination), 'rev-parse', 'HEAD'],
                            check=True, capture_output=True, text=True, timeout=5)
    return result.stdout.strip()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('name', help='new fixture directory name')
    parser.add_argument('--output-root', type=Path, required=True,
                        help='existing isolated directory outside every Git worktree')
    args = parser.parse_args()
    if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_-]{0,63}', args.name):
        parser.error('name must be a single safe directory name')
    root = validate_root(args.output_root)
    destination = root / args.name
    sha = build(destination, output_root=root)
    digest = hashlib.sha256((destination / 'SPEC.md').read_bytes()).hexdigest()
    print(f'fixture={args.name} baseline_sha={sha} spec_sha256={digest}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
